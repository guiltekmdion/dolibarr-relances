	 *
	 * @return void
	 */
	public function testDunningAmountDue()
	{
		$db = $this->savdb;
		$this->createLevels(array(0));
		$socid = $this->createCustomer('amounts@example.com');
		$sources = array(
			'credit note' => $this->createInvoice($socid, -5, 'type = '.Facture::TYPE_CREDIT_NOTE),
